//! RTMP/RTMPS publishing for restream.
//!
//! This crate knows nothing about GStreamer. It takes already-encoded H.264
//! access units (AVCC format, length-prefixed NALUs) and raw AAC frames, wraps
//! them in FLV tag bodies and publishes them over RTMP using `rml_rtmp`'s
//! sans-IO session on top of tokio TCP (optionally wrapped in rustls for
//! `rtmps://`).
//!
//! Design notes
//! - One [`PublishClient`] per destination connection. Media is pushed with
//!   non-blocking `try_send_*` calls; if the socket cannot keep up the caller
//!   receives [`SendError::Lagging`] immediately instead of being blocked, so a
//!   slow destination can never stall the others.
//! - Control traffic generated by the session (acks, pong) goes through a
//!   separate unbounded channel that the writer task prioritises.

pub mod client;
pub mod flv;
pub mod url;

pub use client::{ConnectOptions, PublishClient, SendError};
pub use flv::{aac_frame, aac_sequence_header, avc_frame, avc_sequence_header};
pub use rml_rtmp::sessions::StreamMetadata;
pub use url::PublishUrl;
